"""
SYNTHETIC test data for the research pipeline, written in the exact raw formats the real downloads use
(EPA AirData daily CSV, FIRMS SP CSV, GHCN-Daily access CSV in tenths, HMS shapefile zips, Census gazetteer).

!!! Invented numbers. Used only to check that the code runs end to end and recovers a planted signal. !!!
Smoke is generated by a simple transport rule (fires upwind of a county raise its PM2.5 the same and next day),
so a correct pipeline should find that the wind-aware transport feature helps and the downwind placebo does not.

Usage: RESEARCH_DATA=/tmp/rd python3 research/make_synthetic_research_data.py --seasons 2019 2020
"""
import argparse, csv, datetime as dt, os, shutil, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import config as C  # noqa: E402
import hms as H  # noqa: E402
from build_dataset import haversine, bearing  # noqa: E402

EPA_COLS = ["State Code", "County Code", "Site Num", "Parameter Code", "POC", "Latitude", "Longitude", "Datum",
            "Parameter Name", "Sample Duration", "Pollutant Standard", "Date Local", "Units of Measure", "Event Type",
            "Observation Count", "Observation Percent", "Arithmetic Mean", "1st Max Value", "1st Max Hour", "AQI",
            "Method Code", "Method Name", "Local Site Name", "Address", "State Name", "County Name", "City Name",
            "CBSA Name", "Date of Last Change"]
FIRMS_COLS = ["latitude", "longitude", "bright_ti4", "scan", "track", "acq_date", "acq_time", "satellite", "instrument",
              "confidence", "version", "bright_ti5", "frp", "daynight", "type"]


def main(seasons, seed=11):
    rng = np.random.default_rng(seed)
    real_cty = os.path.join(C.ROOT, "data", "raw", "reference", "ca_counties.csv")   # the real 58-county gazetteer
    os.makedirs(os.path.join(C.DATA, "reference"), exist_ok=True)
    shutil.copy(real_cty, os.path.join(C.DATA, "reference", "ca_counties.csv"))
    rows = list(csv.DictReader(open(real_cty)))
    clat = np.array([float(r["INTPTLAT"]) for r in rows]); clon = np.array([float(r["INTPTLONG"]) for r in rows])
    fips = [r["GEOID"] for r in rows]
    monitored = rng.random(len(rows)) < 0.7                     # ~70% of counties have a PM2.5 monitor

    # weather stations: 30 near random counties
    st_idx = rng.choice(len(rows), 30, replace=False)
    st = [(f"USW000{90000 + i}", clat[j] + rng.normal(0, .1), clon[j] + rng.normal(0, .1)) for i, j in enumerate(st_idx)]
    wdir = os.path.join(C.DATA, "weather", "stations"); os.makedirs(wdir, exist_ok=True)
    wfiles = {sid: open(os.path.join(wdir, f"{sid}.csv"), "w", newline="") for sid, _, _ in st}
    wwriters = {}
    for sid, f in wfiles.items():
        w = csv.writer(f, quoting=csv.QUOTE_ALL)
        w.writerow(["STATION", "DATE", "LATITUDE", "LONGITUDE", "ELEVATION", "NAME", "PRCP", "PRCP_ATTRIBUTES",
                    "TMAX", "TMAX_ATTRIBUTES", "TMIN", "TMIN_ATTRIBUTES", "AWND", "AWND_ATTRIBUTES", "WDF2", "WDF2_ATTRIBUTES"])
        wwriters[sid] = w

    for y in seasons:
        os.makedirs(os.path.join(C.DATA, "epa"), exist_ok=True)
        ef = open(os.path.join(C.DATA, "epa", f"daily_88101_{y}_CA.csv"), "w", newline="")
        ew = csv.writer(ef); ew.writerow(EPA_COLS)
        days = list(C.season_days(y))
        # fire events: start day, location (northern forests mostly), duration, intensity
        events = []
        for _ in range(rng.integers(5, 9)):
            events.append((rng.integers(0, len(days) - 10), rng.uniform(36, 41.8), rng.uniform(-123.8, -119.5),
                           rng.integers(5, 40), rng.uniform(0.5, 3.0)))
        wind_from = 300.0
        prev_smoke = np.zeros(len(rows)); ar = np.zeros(len(rows))
        for di, day in enumerate(days):
            wind_from = (wind_from + rng.normal(0, 25)) % 360 if rng.random() > 0.08 else rng.choice([45.0, 300.0, 200.0])
            # fires today
            pts = []
            for s, la, lo, dur, inten in events:
                if s <= di < s + dur:
                    k = int(inten * 60 * np.sin(np.pi * (di - s + 1) / (dur + 1)))
                    for _ in range(max(k, 1)):
                        pts.append((la + rng.normal(0, .08), lo + rng.normal(0, .08), rng.gamma(2, 15 * inten)))
            pts = np.array(pts) if pts else np.zeros((0, 3))
            # FIRMS file (UTC day = local day for 20:xx UTC overpasses, plus some 09:xx)
            fdir = os.path.join(C.DATA, "firms", str(y)); os.makedirs(fdir, exist_ok=True)
            with open(os.path.join(fdir, f"firms_{day}.csv"), "w", newline="") as f:
                w = csv.writer(f); w.writerow(FIRMS_COLS)
                for la, lo, frp in pts:
                    w.writerow([f"{la:.5f}", f"{lo:.5f}", "330", "0.4", "0.4", str(day), rng.choice(["2042", "2124"]),
                                "N", "VIIRS", rng.choice(["n", "h", "n", "l"]), "1", "290", f"{frp:.2f}", "D", "0"])
                if di % 9 == 0:     # a static industrial source (type 2), must be filtered out
                    w.writerow(["35.40000", "-119.00000", "330", "0.4", "0.4", str(day), "2042", "N", "VIIRS", "h", "1", "290", "300", "D", "2"])
            # smoke transport (the planted signal)
            if len(pts):
                d = haversine(clat[:, None], clon[:, None], pts[None, :, 0], pts[None, :, 1])
                b = bearing(clat[:, None], clon[:, None], pts[None, :, 0], pts[None, :, 1])
                align = np.clip(np.cos(np.radians(b - wind_from)), 0, None)
                smoke = (pts[None, :, 2] * align * np.exp(-d / 220) * (d < 700)).sum(1) * 0.06
            else:
                smoke = np.zeros(len(rows))
            ar = 0.5 * ar + rng.normal(0, 1.2, len(rows))
            pm = np.clip(7 + 2 * np.cos(clat) + ar + 0.6 * smoke + 0.4 * prev_smoke + rng.normal(0, 1.5, len(rows)), 0.5, None)
            prev_smoke = smoke
            for i in np.where(monitored)[0]:
                if rng.random() < 0.06:
                    continue                                   # missing day
                for std in ["PM25 24-hour 2012", "PM25 Annual 2012"]:   # AirData repeats per standard
                    ev = "Included" if pm[i] > 35 else "None"
                    rec = ["06", fips[i][2:], "0001", "88101", "1", f"{clat[i]:.4f}", f"{clon[i]:.4f}", "WGS84",
                           "PM2.5 - Local Conditions", "24 HOUR", std, str(day), "Micrograms/cubic meter (LC)", ev, "1",
                           "100.0", f"{pm[i]:.1f}", f"{pm[i]:.1f}", "0", str(int(pm[i] * 4)), "145", "SYNTHETIC",
                           "SYNTHETIC SITE", "n/a", "California", "n/a", "n/a", "", "2021-05-01"]
                    ew.writerow(rec)
                    if ev == "Included":
                        ew.writerow(rec[:13] + ["Excluded"] + rec[14:16] + ["8.0", "8.0"] + rec[18:])
            # weather in GHCN raw units (tenths)
            for sid, sla, slo in st:
                tmax = 30 - (sla - 34) * 1.5 + rng.normal(0, 3)
                wd = (wind_from + rng.normal(0, 20)) % 360
                wwriters[sid].writerow([sid, str(day), f"{sla:.4f}", f"{slo:.4f}", "50", "SYNTHETIC",
                                        str(int(max(0, rng.normal(-2, 3)) * 10)), ",,W", str(int(tmax * 10)), ",,W",
                                        str(int((tmax - 14) * 10)), ",,W", str(int(rng.uniform(15, 60))), ",,W",
                                        str(int(round(wd / 10) * 10)), ",,W"])
            # HMS: one polygon per active fire cluster, stretched downwind
            polys = []
            for s, la, lo, dur, inten in events:
                if s <= di < s + dur:
                    to = np.radians((wind_from + 180) % 360)
                    L = 2.5 * inten
                    ex, ey = np.sin(to) * L, np.cos(to) * L
                    px, py = -np.cos(to) * 0.6, np.sin(to) * 0.6
                    ring = np.array([[lo + px, la + py], [lo + ex + px, la + ey + py], [lo + ex - px, la + ey - py],
                                     [lo - px, la - py], [lo + px, la + py]])
                    polys.append(("Heavy" if inten > 2 else "Medium" if inten > 1 else "Light", ring))
            hdir = os.path.join(C.DATA, "hms", str(y)); os.makedirs(hdir, exist_ok=True)
            # HMS publishes a file every day, even when no smoke is drawn
            open(os.path.join(hdir, f"hms_smoke{day:%Y%m%d}.zip"), "wb").write(H.write_test_shapefile_zip(polys))
        ef.close()
    for f in wfiles.values():
        f.close()
    open(os.path.join(C.DATA, "SYNTHETIC_DATA_README.txt"), "w").write("SYNTHETIC research test data. Never report as results.\n")
    print(f"synthetic research data for {seasons} -> {C.DATA}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--seasons", type=int, nargs="*", default=[2019, 2020])
    main(ap.parse_args().seasons)
